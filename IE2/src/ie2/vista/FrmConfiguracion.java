    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if (controlador.cargarPartidaGuardada()) {
            FrmSimulacion frmSim = new FrmSimulacion(controlador);
            frmSim.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo cargar la simulación guardada.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       int plantas = (Integer) jSpinner1.getValue();
        int conejos = (Integer) jSpinner2.getValue();
        int lobos = (Integer) jSpinner3.getValue();
        int turnos = (Integer) jSpinner4.getValue();
        Clima clima = Clima.valueOf(jComboBox1.getSelectedItem().toString());

        String error = controlador.iniciarNuevaSimulacion(plantas, conejos, lobos, clima, turnos);
        if (error != null) {
            JOptionPane.showMessageDialog(this, error, "Error de Validación", JOptionPane.ERROR_MESSAGE);
        } else {
            FrmSimulacion frmSim = new FrmSimulacion(controlador);
            frmSim.setVisible(true);
            this.dispose();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

