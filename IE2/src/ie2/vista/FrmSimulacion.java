    public void actualizarPantalla() {
        lblTurno.setText("Turno: " + controlador.getTurnoActual() + " / " + controlador.getTurnosTotales());
        lblClima.setText("Clima: " + controlador.getClimaActual());
        lblPlantas.setText("Plantas: " + controlador.getCantPlantas());
        lblConejos.setText("Conejos: " + controlador.getCantConejos());
        lblLobos.setText("Lobos: " + controlador.getCantLobos());

        DefaultTableModel modelTabla = (DefaultTableModel) tblEntidades.getModel();
        modelTabla.setRowCount(0);

        for (Entidad e : controlador.getEntidadesVivas()) {
            modelTabla.addRow(new Object[]{
                e.getNombre(),
                e.getClass().getSimpleName(),
                e.getEnergia(),
                e.getEdad(),
                e.isViva() ? "VIVA" : "MUERTA"
            });
        }

        boolean sePuedeIntervenir = controlador.sePuedeIntervenir();
        btnCambiarClima.setEnabled(sePuedeIntervenir);
        btnAgregarEntidad.setEnabled(sePuedeIntervenir);
        btnOmitir.setEnabled(sePuedeIntervenir);

        if (sePuedeIntervenir) {
            lblEstado.setText("¡Turno de intervención disponible!");
        } else {
            lblEstado.setText("Simulación en curso...");
        }

        if (controlador.simulacionTerminada()) {
            btnAvanzar.setEnabled(false);
            btnCambiarClima.setEnabled(false);
            btnAgregarEntidad.setEnabled(false);
            btnOmitir.setEnabled(false);
            lblEstado.setText("SIMULACIÓN FINALIZADA.");

            FrmReporte frmReporte = new FrmReporte(controlador);
            frmReporte.setVisible(true);
        }
    }

    private void btnAvanzarActionPerformed(java.awt.event.ActionEvent evt) {                                          
        controlador.avanzarTurno();
        modelEventos.addElement("Turno " + controlador.getTurnoActual() + " procesado.");
        actualizarPantalla();
    }                                         

    private void btnCambiarClimaActionPerformed(java.awt.event.ActionEvent evt) {                                                
        Clima nuevo = (Clima) JOptionPane.showInputDialog(this, 
                "Seleccione el nuevo clima:", "Cambiar Clima", 
                JOptionPane.QUESTION_MESSAGE, null, Clima.values(), Clima.SOLEADO);
        if (nuevo != null) {
            controlador.cambiarClima(nuevo);
            modelEventos.addElement("Intervención: Clima a " + nuevo);
            actualizarPantalla();
        }
    }                                               

    private void btnAgregarEntidadActionPerformed(java.awt.event.ActionEvent evt) {                                                  
        String[] opciones = {"Planta", "Conejo", "Lobo"};
        String eleccion = (String) JOptionPane.showInputDialog(this, 
                "Seleccione la entidad a agregar:", "Añadir Entidad", 
                JOptionPane.QUESTION_MESSAGE, null, opciones, opciones[0]);
        if (eleccion != null) {
            boolean exito = controlador.agregarEntidad(eleccion);
            if (exito) {
                modelEventos.addElement("Intervención: Se agregó " + eleccion);
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo agregar (Límite máximo alcanzado).", "Aviso", JOptionPane.WARNING_MESSAGE);
            }
            actualizarPantalla();
        }
    }                                                 

    private void btnOmitirActionPerformed(java.awt.event.ActionEvent evt) {                                        
        modelEventos.addElement("Intervención omitida.");
        actualizarPantalla();
    }

